static inline bool OutcomeWordEntry(const Lufia2CpuState *cpu) {
    return TableServiceReady(cpu, false) && !cpu->accumulator_is_8_bit &&
        !cpu->index_is_8_bit;
}

static inline void ClearOutcomeCounters(const Lufia2Memory *memory,
    Lufia2CpuState *cpu) {
    OpLdx(cpu, 0u);
    OpLdy(cpu, 5u);
    do {
        OpStz(memory, cpu, OpAbsX(cpu, OUTCOME_LINE_COUNTERS));
        OpInx(cpu);
        OpInx(cpu);
        OpDey(cpu);
    } while (!cpu->zero);
}

static inline void SetOutcomeTextMode(const Lufia2Memory *memory,
    Lufia2CpuState *cpu, uint8_t mode) {
    OpSepWidths(cpu, 0x20u);
    OpLoadA(cpu, mode);
    OpSta(memory, cpu, OpAbs(cpu, OUTCOME_TEXT_MODE));
    OpLoadA(cpu, 0x84u);
    OpSta(memory, cpu, OpDp(cpu, OUTCOME_TEXT_BANK));
}

